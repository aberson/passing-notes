def test_list_and_close_use_exact_synthetic_receipt(
    case: tuple[FakeStore, Path, Path, list[Any]],
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    store, state_root, launcher, processes = case
    monkeypatch.setenv("LOCALAPPDATA", str(state_root.parent))
    monkeypatch.setattr(cleanup.Store, "open", lambda: store)
    monkeypatch.setattr(cleanup, "_snapshot", lambda: processes)
    called: list[Any] = []
    monkeypatch.setattr(cleanup, "_terminate_checked", lambda tree: called.append(tree))

    assert cleanup.main(["--project", "example", "--list"]) == 0
    row = json.loads(capsys.readouterr().out)
    assert row == {
        "lane": "api",
        "pid": 100,
        "created": processes[0].created,
        "launcher": str(launcher),
        "processes": 3,
        "closeable": True,
    }
    assert not called
    assert (
        cleanup.main(
            [
                "--project",
                "example",
                "--lane",
                row["lane"],
                "--close",
                "--pid",
                str(row["pid"]),
                "--created",
                row["created"],
                "--launcher",
                row["launcher"],
            ]
        )
        == 0
    )
    assert len(called) == 1 and [p.pid for p in called[0]] == [100, 101, 102]
