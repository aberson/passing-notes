SESSION = "01234567-89ab-cdef-0123-456789abcdef"
# The invoking process: in another window, present in every snapshot (own-pid guard).
INVOKER_PID = 4242


def invoker(pid: int = INVOKER_PID, parent: int = 1) -> Any:
    return cleanup.Process(pid, parent, "python.exe", "python close.py", "2026-11-19T12:05:00Z")


class FakeStore:
    def __init__(self, root: Path, state: str = "done", window: str | None = SESSION) -> None:
        self.root = root
        self.card = SimpleNamespace(
            project="example",
            lane="api",
            host="codex",
            state=state,
            window=window,
            checkout="",
            updated_utc="2026-11-19T12:10:00Z",
        )
        self.others: list[Any] = []
        (root / "cards" / "example").mkdir(parents=True)

    def load_card(self, project: str, lane: str) -> object:
        assert (project, lane) == ("example", "api")
        return self.card

    def scan_cards(self, project: str) -> tuple[list[Any], list[Any]]:
        assert project == "example"
        return [self.card, *self.others], []


def save_binding(
    store: FakeStore,
    *,
    project: str = "example",
    lane: str = "api",
    host: str = "codex",
    session: str = SESSION,
    bound_utc: str = "2026-11-19T12:00:05Z",
) -> None:
    folder = store.root / "wake" / project
    folder.mkdir(parents=True, exist_ok=True)
    (folder / f"{lane}.binding.json").write_text(
        json.dumps(
            {
                "project": project,
                "lane": lane,
                "host": host,
                "session_id": session,
                "permission_mode": "queue" if host == "codex" else "default",
                "bound_utc": bound_utc,
            }
        ),
        encoding="utf-8",
    )


