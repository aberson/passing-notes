def test_hand_opened_claude_window_is_never_closeable(
    claude_case: ClaudeCase,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    _, state_root, launcher, processes, _ = claude_case
    launcher.unlink()
    cleanup.launch_record_path(launcher).unlink()
    # An operator-opened PowerShell window running claude: no generated launcher.
    processes[0] = cleanup.Process(100, 1, "powershell.exe", "powershell.exe", CLAUDE_CREATED)
    monkeypatch.setattr(cleanup, "_windows_args", lambda command: ["powershell.exe"])
    monkeypatch.setattr(cleanup, "_snapshot", lambda: processes)
    monkeypatch.setattr(cleanup, "_terminate_checked", lambda tree: pytest.fail("must refuse"))
    assert cleanup.main(["--project", "example", "--list"]) == 0
    assert capsys.readouterr().out == ""
    assert cleanup.main(["--project", "example", "--public-inventory"]) == 0
    output = capsys.readouterr().out
    assert json.loads(output) == {
        "project": "example",
        "lane": "api",
        "kind": "session-process-unverified",
        "closeable": False,
        "reason": "no-verified-launcher",
    }
    _assert_no_private_claude_fields(output, launcher, processes)
    argv = ["--project", "example", "--lane", "api", "--close", "--pid", "100"]
    argv += ["--created", CLAUDE_CREATED, "--launcher", str(launcher)]
    assert cleanup.main(argv) == 2
    assert "refused: launcher-file-unverified" in capsys.readouterr().err
    # A guessed path outside the lane-open folder is refused before anything is read.
    guessed = state_root.parent / "elsewhere" / launcher.name
    argv[-1] = str(guessed)
    assert cleanup.main(argv) == 2
    assert "refused: launcher-path-unexpected" in capsys.readouterr().err


def test_claude_inventory_asks_the_host_once_and_codex_never(
    case: tuple[FakeStore, Path, Path, list[Any]],
    claude_case: ClaudeCase,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    _, _, _, processes, sessions = claude_case
    calls: list[int] = []

    def listing() -> list[Any]:
        calls.append(1)
        return sessions

    monkeypatch.setattr(cleanup, "_claude_sessions", listing)
    monkeypatch.setattr(cleanup, "_snapshot", lambda: processes)
    assert cleanup.main(["--project", "example", "--public-inventory"]) == 0
