"""Synthetic safety checks for operator-authorized done-window cleanup.

No test opens or terminates a real process.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path
from types import SimpleNamespace
from typing import Any, cast

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "skills/lane-close/scripts/close_done_window.py"
spec = importlib.util.spec_from_file_location("close_done_window", SCRIPT)
assert spec and spec.loader
cleanup: Any = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = cleanup
spec.loader.exec_module(cleanup)


class FakeStore:
    def __init__(self, root: Path, state: str = "done", window: str = "session-a") -> None:
        self.root = root
        self.card = SimpleNamespace(
            project="example",
            lane="api",
            host="codex",
            state=state,
            window=window,
            updated_utc="2026-11-19T12:10:00Z",
        )
        self.others: list[Any] = []
        (root / "cards" / "example").mkdir(parents=True)

    def load_card(self, project: str, lane: str) -> object:
        assert (project, lane) == ("example", "api")
        return self.card

    def scan_cards(self, project: str) -> tuple[list[Any], list[Any]]:
        assert project == "example"
        return [self.card, *self.others], []


@pytest.fixture
def case(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> tuple[FakeStore, Path, Path, list[Any]]:
    store = FakeStore(tmp_path / "store")
    state_root = tmp_path / "passing-notes-lanes"
    folder = state_root / "example"
    folder.mkdir(parents=True)
    launcher = folder / "api-20261119T120000Z.ps1"
    launcher.write_text(
        "# Generated by the lane-open skill.\n& codex -C 'tmp' $prompt\n", encoding="utf-8"
    )
    root = cleanup.Process(
        100,
        1,
        "powershell.exe",
        f'"powershell.exe" -NoExit -ExecutionPolicy Bypass -File "{launcher}"',
        "2026-11-19T12:00:00Z",
    )
    child = cleanup.Process(101, 100, "node.exe", "node codex.js", "2026-11-19T12:00:01Z")
    console = cleanup.Process(102, 100, "conhost.exe", "conhost.exe 0x4", "2026-11-19T12:00:01Z")
    monkeypatch.setattr(
        cleanup,
        "_windows_args",
        lambda command: (
            [
                "powershell.exe",
                "-NoExit",
                "-ExecutionPolicy",
                "Bypass",
                "-File",
                str(launcher),
            ]
            if command == root.command
            else []
        ),
    )
    return store, state_root, launcher, [root, child, console]


def assess(case: tuple[FakeStore, Path, Path, list[Any]]) -> list[Any]:
    store, state_root, launcher, processes = case
    return cast(
        list[Any],
        cleanup.assess(store, state_root, "example", "api", launcher, processes[0], processes),
    )


def test_exact_done_launcher_and_codex_tree_is_closeable(
    case: tuple[FakeStore, Path, Path, list[Any]],
) -> None:
    assert [p.pid for p in assess(case)] == [100, 101, 102]


@pytest.mark.parametrize("state", ["active", "waiting", "blocked", "idle"])
def test_live_card_refused(case: tuple[FakeStore, Path, Path, list[Any]], state: str) -> None:
    case[0].card.state = state
    with pytest.raises(cleanup.Refused, match="card must be done"):
        assess(case)


def test_shared_session_refused(case: tuple[FakeStore, Path, Path, list[Any]]) -> None:
    case[0].others.append(
        SimpleNamespace(project="example", lane="other", window="session-a", state="waiting")
    )
    with pytest.raises(cleanup.Refused, match="shares this window"):
        assess(case)


def test_invoking_window_refused(
    case: tuple[FakeStore, Path, Path, list[Any]], monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(cleanup.os, "getpid", lambda: 101)
    with pytest.raises(cleanup.Refused, match="invoking window"):
        assess(case)


def test_launcher_and_process_mismatch_refused(
    case: tuple[FakeStore, Path, Path, list[Any]],
) -> None:
    store, state_root, launcher, processes = case
    wrong = launcher.with_name("other-20261119T120000Z.ps1")
    with pytest.raises(cleanup.Refused, match="launcher path"):
        cleanup.assess(store, state_root, "example", "api", wrong, processes[0], processes)
    monkey = cleanup._windows_args
    try:
        cleanup._windows_args = lambda command: [
            "powershell.exe",
            "-NoExit",
            "-ExecutionPolicy",
            "Bypass",
            "-File",
            str(wrong),
        ]
        with pytest.raises(cleanup.Refused, match="process identity"):
            assess(case)
    finally:
        cleanup._windows_args = monkey


def test_ambiguous_and_unfamiliar_children_refused(
    case: tuple[FakeStore, Path, Path, list[Any]],
) -> None:
    processes = case[3]
    processes.append(
        cleanup.Process(103, 1, "powershell.exe", processes[0].command, processes[0].created)
    )
    with pytest.raises(cleanup.Refused, match="ambiguous"):
        assess(case)
    processes.pop()
    processes.append(
        cleanup.Process(103, 101, "python.exe", "python server.py", "2026-11-19T12:00:02Z")
    )
    with pytest.raises(cleanup.Refused, match="unknown or shared child"):
        assess(case)


def test_reused_launcher_shell_refused(case: tuple[FakeStore, Path, Path, list[Any]]) -> None:
    processes = case[3]
    processes.append(cleanup.Process(103, 100, "node.exe", "node codex.js", "2026-11-19T12:11:00Z"))
    with pytest.raises(cleanup.Refused, match="multiple host processes"):
        assess(case)
